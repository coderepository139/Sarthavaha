interface PDFContext {
  doc: jsPDF;
  y: number;
  pageNumber: number;
  margin: number;
  contentWidth: number;
  title: string;
}

/**
 * Draw header banner, footer, and borders on every page
 */
function drawPageShell(ctx: PDFContext, isTitlePage: boolean = false) {
  const { doc, title, margin, contentWidth } = ctx;
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // Draw elegant geometric background details
  if (isTitlePage) {
    // Top-right branding polygon
    doc.setFillColor(30, 27, 75); // Navy
    doc.triangle(pageWidth, 0, pageWidth - 60, 0, pageWidth, 60, 'F');
    doc.setFillColor(6, 182, 212); // Cyan accent bar
    doc.rect(pageWidth - 3, 0, 3, 100, 'F');
    return;
  }

  // Running Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(30, 27, 75);
  doc.text('SARTHAVAHA CO-PILOT', margin, 15);
  
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  doc.text('|   CLIENT PRESENTATION REPORT', margin + 42, 15);

  // Top dividing line
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.3);
  doc.line(margin, 18, pageWidth - margin, 18);

  // Running Footer
  doc.line(margin, pageHeight - 15, pageWidth - margin, pageHeight - 15);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text('CONFIDENTIAL — GENERATED BY SARTHAVAHA MARKETING INTELLIGENCE', margin, pageHeight - 10);
  
  // Page number right-aligned
  const pageStr = `Page ${ctx.pageNumber}`;
  doc.text(pageStr, pageWidth - margin - doc.getTextWidth(pageStr), pageHeight - 10);
}

/**
 * Handle page overflow and add a new page cleanly
 */
function checkPageOverflow(ctx: PDFContext, heightNeeded: number) {
  const pageHeight = ctx.doc.internal.pageSize.getHeight();
  const limit = pageHeight - 25; // leave room for footer

  if (ctx.y + heightNeeded > limit) {
    ctx.doc.addPage();
    ctx.pageNumber += 1;
    ctx.y = 30; // reset Y below header line
    drawPageShell(ctx, false);
  }
}

/**
 * Render wrapped blocks of text supporting headers, bold markers, and lists
 */
function renderMarkdownText(ctx: PDFContext, text: string) {
  const { doc, margin, contentWidth } = ctx;
  const lines = text.split('\n');

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(51, 65, 85);

  for (let line of lines) {
    line = line.trim();
    if (!line) {
      // Empty line - add small spacing
      ctx.y += 4;
      continue;
    }

    // Determine line formatting
    let fontSize = 10;
    let isBold = false;
    let isHeader = false;
    let indent = 0;
    let cleanLine = line;

    // Headings starting with ### or similar
    if (line.startsWith('###')) {
      fontSize = 12;
      isBold = true;
      isHeader = true;
      cleanLine = line.replace(/^###\s*/, '');
    } else if (line.startsWith('##')) {
      fontSize = 13;
      isBold = true;
      isHeader = true;
      cleanLine = line.replace(/^##\s*/, '');
    } else if (line.startsWith('#')) {
      fontSize = 15;
      isBold = true;
      isHeader = true;
      cleanLine = line.replace(/^#\s*/, '');
    }
    // Bullet lists
    else if (line.startsWith('- ') || line.startsWith('* ')) {
      indent = 5;
      cleanLine = '•  ' + line.substring(2);
    }
    // Numbered lists
    else if (/^\d+\.\s+/.test(line)) {
      indent = 5;
      cleanLine = line;
    }
    // Highlighted headers within text (e.g., **Title**)
    else if (line.startsWith('**') && line.endsWith('**') && line.length < 100) {
      fontSize = 11;
      isBold = true;
      cleanLine = line.replace(/\*\*/g, '');
    }

    // Set font style
    doc.setFont('helvetica', isBold ? 'bold' : 'normal');
    doc.setFontSize(fontSize);
    
    if (isHeader) {
      doc.setTextColor(30, 27, 75); // Navy for headings
      ctx.y += 3; // add padding before header
    } else {
      doc.setTextColor(51, 65, 85); // Slate for body text
    }

    // Wrap the clean line to the printable width
    const wrappedLines: string[] = doc.splitTextToSize(cleanLine, contentWidth - indent);
    
    for (const wrappedLine of wrappedLines) {
      // 6 units line height
      const lineHeight = fontSize === 15 ? 8 : fontSize === 13 ? 7 : fontSize === 12 ? 6.5 : 5.5;
      checkPageOverflow(ctx, lineHeight);
      
      doc.text(wrappedLine, margin + indent, ctx.y);
      ctx.y += lineHeight;
    }

    // Small separation space after headings or paragraphs
    if (isHeader) {
      ctx.y += 2;
    } else {
      ctx.y += 1.5;
    }
  }
}

/**
 * Export Competitive Intelligence Report as clean PDF
 */
export function exportCompetitiveIntelligenceReport(
  niche: string,
  audience: string,
  reportContent: string,
  userEmail: string
) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const margin = 20;
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const contentWidth = pageWidth - (margin * 2);

  const ctx: PDFContext = {
    doc,
    y: 0,
    pageNumber: 1,
    margin,
    contentWidth,
    title: 'Competitive Intelligence Report'
  };

  // ================= TITLE PAGE =================
  drawPageShell(ctx, true);

  // Large Logo/Icon Graphic
  doc.setDrawColor(79, 70, 229); // Indigo
  doc.setLineWidth(1.5);
  doc.rect(margin, 40, 15, 15);
  doc.setFillColor(6, 182, 212); // Cyan
  doc.rect(margin + 5, 45, 15, 15, 'FD');

  ctx.y = 80;
  
  // Tagline/Category
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(6, 182, 212); // Cyan
  doc.text('SARTHAVAHA MARKETING SYSTEMS', margin, ctx.y);
  ctx.y += 8;

  // Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(28);
  doc.setTextColor(30, 27, 75); // Deep Navy
  const wrappedTitle = doc.splitTextToSize('Competitive\nIntelligence Report', contentWidth);
  doc.text(wrappedTitle, margin, ctx.y);
  ctx.y += 24;

  // Subtitle
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(12);
  doc.setTextColor(100, 116, 139);
  doc.text('Autonomous Market Scan & Competitive Ad Placement Insights', margin, ctx.y);
  ctx.y += 20;

  // Horizontal divider
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(margin, ctx.y, pageWidth - margin, ctx.y);
  ctx.y += 15;

  // Metadata block
  doc.setFillColor(248, 250, 252);
  doc.rect(margin, ctx.y, contentWidth, 40, 'F');
  
  // Metadata fields
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(30, 27, 75);
  doc.text('TARGET MARKET:', margin + 6, ctx.y + 10);
  doc.text('TARGET AUDIENCE:', margin + 6, ctx.y + 18);
  doc.text('CLIENT ACCOUNT:', margin + 6, ctx.y + 26);
  doc.text('DATE GENERATED:', margin + 6, ctx.y + 34);

  doc.setFont('helvetica', 'normal');
  doc.setTextColor(51, 65, 85);
  doc.text(niche, margin + 45, ctx.y + 10);
  doc.text(audience || 'Broad / Optimized demographic', margin + 45, ctx.y + 18);
  doc.text(userEmail || 'guest@sarthavaha.io', margin + 45, ctx.y + 26);
  
  const currentDateStr = new Date().toLocaleDateString('en-US', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  });
  doc.text(currentDateStr, margin + 45, ctx.y + 34);

  // Footer on cover
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(30, 27, 75);
  doc.text('SARTHAVAHA CO-PILOT SYSTEM', margin, pageHeight - 20);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(148, 163, 184);
  doc.text('CONFIDENTIAL PREPARATION FOR INTERNAL STRATEGY & CLIENT PITCHING ONLY', margin, pageHeight - 15);

  // ================= CONTENT PAGES =================
  doc.addPage();
  ctx.pageNumber = 2;
  ctx.y = 32;
  drawPageShell(ctx, false);

  // Section header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(30, 27, 75);
  doc.text('Compiled Market Intelligence findings', margin, ctx.y);
  ctx.y += 4;
  
  // Underline bar
  doc.setFillColor(79, 70, 229); // Indigo
  doc.rect(margin, ctx.y, 25, 1, 'F');
  ctx.y += 8;

  // Body content
  renderMarkdownText(ctx, reportContent);

  // Trigger Save
  const cleanNicheName = niche.replace(/[^a-zA-Z0-9]/g, '_').toLowerCase().substring(0, 20);
  doc.save(`Sarthavaha_Competitive_Intelligence_${cleanNicheName}.pdf`);
}

